// SYNTHETIC DEMO provider. Used only when the client marks a request as
// belonging to one of the bundled synthetic demo cases. It returns scripted
// responses that are labelled "demo" in every envelope; it never analyses
// real data and is never used as a fallback for real cases.
import type {
  AICapability,
  AnalyzeImagesRequest,
  ArgueTurn,
  CaseRequest,
  Discussion,
  DiscussionRequest,
  ExtractRequest,
  GeneratedCase,
  Lesson,
  PresentationRequest,
  ReasoningEvaluation,
  RoundNoteRequest,
  TeachingRequest,
  TimelineRequest,
  TranscribeRequest,
} from '../../../shared/ai';
import {
  demoImageAnalysis,
  demoLabExtraction,
  demoMedicationExtraction,
  demoPatientExtraction,
  findDemoCase,
  type DemoCase,
  type DemoDoc,
} from '../../../shared/demo';
import { DEPARTMENTS, type DepartmentId } from '../../../shared/departments';
import { buildTemplatePresentation } from '../../../shared/presentation';
import { keywordEvaluate, TRAINING_BANK } from '../../../shared/training';
import type { CompetencyDomain } from '../../../shared/domain';
import type { AIProvider, AIResult } from './AIProvider';
import { AIError } from './errors';

const DEMO_NOTE = 'SYNTHETIC DEMO RESPONSE — scripted for a fictional case, not generated by AI.';

const ARGUE_SCRIPT: Array<{ focus: ArgueTurn['focus']; q: string }> = [
  { focus: 'why', q: 'Why? What is the clinical problem you are trying to solve with this recommendation?' },
  { focus: 'evidence', q: 'What patient-specific evidence supports your recommendation? Name the data points.' },
  { focus: 'alternative', q: 'What alternative would you consider, and why did you not choose it?' },
  { focus: 'risk', q: 'What are the risks of your recommendation for this patient?' },
  { focus: 'monitoring', q: 'What would you monitor, how often, and what would make you change course?' },
  { focus: 'missing_data', q: 'What information is missing that could change your decision?' },
];

const DEFENSE_SCRIPT: Array<{ focus: ArgueTurn['focus']; q: string }> = [
  { focus: 'why', q: 'Why is this a drug-related problem and not just a disease problem?' },
  { focus: 'evidence', q: 'What evidence supports your assessment — patient data and literature?' },
  { focus: 'alternative', q: 'Why this drug, and why not the alternative?' },
  { focus: 'dose', q: 'Was the dose appropriate for this patient’s renal and hepatic function?' },
  { focus: 'monitoring', q: 'What monitoring is required, and when?' },
  { focus: 'risk', q: 'What would you do if renal function worsened or the patient deteriorated?' },
  { focus: 'missing_data', q: 'What information was missing, and how did that limit you?' },
  { focus: 'outcome', q: 'Was your recommendation accepted, and what did you learn from this case?' },
];

export class DemoProvider implements AIProvider {
  readonly name = 'demo' as const;
  readonly model = 'synthetic-demo';
  readonly configured = true;
  readonly capabilities: readonly AICapability[] = ['text', 'vision', 'audio'];
  private readonly demo: DemoCase | undefined;
  private readonly doc: DemoDoc | undefined;

  constructor(caseKey: string | undefined, docKey?: string) {
    this.demo = findDemoCase(caseKey);
    this.doc = this.demo?.docs.find((d) => d.key === docKey);
  }

  static isDemoCase(caseKey: string | undefined): boolean {
    return Boolean(findDemoCase(caseKey));
  }

  async probe(): Promise<void> {}

  private ok<T>(data: T, extra: string[] = []): AIResult<T> {
    return { data, warnings: [DEMO_NOTE, ...extra] };
  }

  private requireCase(): DemoCase {
    if (!this.demo) throw new AIError('REQUEST_INVALID', { details: ['Unknown demo case.'] });
    return this.demo;
  }

  private requireDoc(): DemoDoc {
    if (!this.doc)
      throw new AIError('REQUEST_INVALID', {
        details: ['The demo provider only reads the bundled synthetic documents. Configure GEMINI_API_KEY to analyse your own sources.'],
      });
    return this.doc;
  }

  async analyzeImages(_req: AnalyzeImagesRequest) {
    return this.ok(demoImageAnalysis(this.requireDoc()));
  }

  async extractPatientData(_req: ExtractRequest) {
    return this.doc ? this.ok(demoPatientExtraction(this.doc)) : this.ok({ items: [], notDocumented: [] }, ['Free text is not analysed in demo mode.']);
  }

  async extractMedications(_req: ExtractRequest) {
    return this.doc ? this.ok(demoMedicationExtraction(this.doc)) : this.ok({ medications: [] }, ['Free text is not analysed in demo mode.']);
  }

  async extractLabs(_req: ExtractRequest) {
    return this.doc ? this.ok(demoLabExtraction(this.doc)) : this.ok({ labs: [] }, ['Free text is not analysed in demo mode.']);
  }

  async transcribeAudio(_req: TranscribeRequest) {
    const c = this.requireCase();
    return this.ok(
      { transcript: c.roundNoteText, detectedLanguage: 'en' as const, uncertainSegments: [], confidence: 0.9 },
      ['Demo mode returns a scripted transcript; your recording was not analysed.'],
    );
  }

  async buildTimeline(_req: TimelineRequest) {
    return this.ok(this.requireCase().timeline);
  }

  async analyzeCase(_req: CaseRequest) {
    return this.ok(this.requireCase().analysis);
  }

  async identifyPotentialDRPs(_req: CaseRequest) {
    return this.ok(this.requireCase().drps);
  }

  async generateClinicalDiscussion(req: DiscussionRequest) {
    const c = this.requireCase();
    const first = c.drps.drps[0];
    const sameAsFirst = (req.drp.medication ?? '') === (first?.medication ?? '') && req.drp.category === first?.category;
    if (sameAsFirst) return this.ok(c.discussion);
    const match = c.drps.drps.find((d) => d.category === req.drp.category && (d.medication ?? '') === (req.drp.medication ?? ''));
    const src = match ?? {
      description: req.drp.description,
      patientEvidence: req.drp.patientEvidence,
      clinicalSignificance: 'Not scripted for this demo DRP.',
      evidenceBasis: 'Not scripted for this demo DRP.',
      suggestedAction: 'Discuss with your preceptor.',
      monitoring: '',
      followUp: '',
    };
    const discussion: Discussion = {
      problem: src.description,
      patientEvidence: src.patientEvidence,
      assessment: src.clinicalSignificance,
      evidenceSummary: src.evidenceBasis,
      referencesToConsult: ['Appropriate drug reference', 'Local protocol'],
      options: [{ option: src.suggestedAction, benefits: [], risks: [] }],
      recommendationDraft: src.suggestedAction,
      rationale: src.clinicalSignificance,
      monitoring: src.monitoring ? [src.monitoring] : [],
      followUp: src.followUp,
      questionsForStudent: ['What patient data would change this recommendation?', 'What would you monitor first?'],
    };
    return this.ok(discussion);
  }

  async generateMonitoringPlan(_req: CaseRequest) {
    return this.ok(this.requireCase().monitoring);
  }

  async generateFollowUp(_req: CaseRequest) {
    return this.ok(this.requireCase().followUp);
  }

  async structureRoundNote(req: RoundNoteRequest) {
    const c = this.requireCase();
    if (req.text.trim().slice(0, 25) === c.roundNoteText.slice(0, 25)) return this.ok(c.roundNote);
    const sentences = req.text.split(/(?<=[.!?])\s+/).map((s) => s.trim()).filter(Boolean);
    return this.ok(
      { summary: sentences[0] ?? '', changes: sentences, medicationChanges: [], decisions: [], possibleNewDrps: [], followUpsRequired: [], tasks: [] },
      ['Demo mode only splits custom notes into sentences.'],
    );
  }

  async generatePresentation(req: PresentationRequest) {
    const c = this.requireCase();
    return this.ok(
      buildTemplatePresentation(req.context, req.minutes, {
        monitoring: c.monitoring.items.map((m) => `${m.parameter}: ${m.target} (${m.frequency})`),
        followUps: c.followUp.items.map((f) => `${f.window.replace('_', ' ')}: ${f.reassess}`),
        learningPoints: c.teaching.questions.map((q) => q.keyPoints[0]).filter(Boolean),
      }),
    );
  }

  async generateTeachingQuestions(_req: TeachingRequest) {
    return this.ok(this.requireCase().teaching);
  }

  async evaluateStudentReasoning(req: TeachingRequest) {
    const reference =
      req.referencePoints.length > 0
        ? req.referencePoints
        : this.demo?.teaching.questions.find((q) => q.question === req.question)?.keyPoints ?? [];
    const domain: CompetencyDomain =
      this.demo?.teaching.questions.find((q) => q.question === req.question)?.domain ??
      TRAINING_BANK.flatMap((e) => e.questions).find((q) => q.question === req.question)?.domain ??
      'clinical_reasoning';
    const { covered, missed } = keywordEvaluate(req.answer ?? '', reference);
    const ratio = reference.length ? covered.length / reference.length : 0;
    const evaluation: ReasoningEvaluation = {
      overall: ratio >= 0.75 ? 'on_track' : ratio >= 0.4 ? 'partially' : 'needs_work',
      correctElements: covered,
      missedElements: missed,
      inaccuracies: [],
      explanation:
        'SYNTHETIC DEMO FEEDBACK: your answer was compared with the reference points by keyword matching only. It was not evaluated by AI. Configure GEMINI_API_KEY for full preceptor feedback.',
      nextTimeStrategy: missed.length ? `Before answering, check whether you addressed: ${missed.slice(0, 2).join('; ')}.` : 'Keep linking each point to patient-specific evidence.',
      domains: [domain],
      knowledgeGaps: missed.slice(0, 3).map((m) => ({ topic: m.slice(0, 120), domain })),
    };
    return this.ok(evaluation);
  }

  async continueDialogue(req: TeachingRequest) {
    const script = req.mode === 'defense' ? DEFENSE_SCRIPT : ARGUE_SCRIPT;
    const studentTurns = req.history.filter((h) => h.role === 'student').length;
    if (studentTurns > script.length) {
      const turn: ArgueTurn = {
        acknowledgement: 'Thank you — that completes the scripted demo dialogue.',
        challenge: '',
        focus: 'summary',
        done: true,
        summary: {
          strengths: ['You engaged with every challenge question.'],
          gaps: ['Demo mode cannot judge content. Use Gemini for real feedback.'],
          learningPoint: 'Always connect a recommendation to patient evidence, alternatives, risks and monitoring.',
        },
      };
      return this.ok(turn);
    }
    const step = script[Math.max(0, studentTurns - 1)] ?? script[0]!;
    return this.ok({ acknowledgement: studentTurns > 1 ? 'Noted.' : 'Let us examine your reasoning.', challenge: step.q, focus: step.focus, done: false } satisfies ArgueTurn);
  }

  async generateTrainingCase(req: TeachingRequest) {
    const pool = TRAINING_BANK.filter((e) => !req.level || e.level === req.level);
    const pick = pool[0] ?? TRAINING_BANK[0]!;
    const generated: GeneratedCase = {
      title: `${pick.title} (built-in exercise)`,
      scenario: pick.scenario,
      questions: pick.questions.map((q) => ({ question: q.question, domain: q.domain, keyPoints: q.keyPoints })),
    };
    return this.ok(generated, ['Demo mode returns a built-in exercise instead of generating a new case.']);
  }

  async generateLesson(req: TeachingRequest) {
    const dept = DEPARTMENTS[(req.department ?? 'internal_medicine') as DepartmentId] ?? DEPARTMENTS.internal_medicine;
    const lesson: Lesson = {
      topic: req.focus ?? dept.learningTopics[0] ?? 'Clinical reasoning',
      keyConcepts: dept.drpPrompts,
      commonPitfalls: ['Not linking the recommendation to patient-specific data', 'Forgetting to define monitoring and follow-up'],
      practiceQuestion: dept.drpPrompts[0] ?? 'What is the most important medication-related problem?',
      referencesToConsult: ['Drug monograph', 'Local protocol'],
    };
    return this.ok(lesson, ['Demo lesson built from the department profile.']);
  }
}
